#Bài 4: Tính toán trên Tuple
#Cho tuple:
#numbers = (2, 4, 6, 8, 10)
#1.	Tính tổng các phần tử.
#2.	Tìm giá trị lớn nhất và nhỏ nhất.
numbers = (2, 4, 6, 8, 10)
#1.	Tính tổng các phần tử.
Tong = sum(numbers)
print("Tuple:", numbers)
print("Tổng các phần tử:",Tong)
#2.	Tìm giá trị lớn nhất và nhỏ nhất.
Max_Val = max(numbers)
Min_Val = min(numbers)
print("Giá trị lớn nhất:",Max_Val)
print("Giá trị nhỏ nhất:",Min_Val)
